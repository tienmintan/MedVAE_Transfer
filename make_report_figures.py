"""
make_report_figures.py: build the figures and LaTeX tables from cached result CSVs.

The experiments do not need to be re-run: the CSVs hold the numbers. The
script reads them, renders figures as 300 dpi PDFs, and writes LaTeX table
bodies (booktabs) to tables.tex.

Several result directories contain the same table from runs with different
seed counts; --audit lists them so the intended source can be chosen
(--frontier).

Inputs:  CSVs under --results (frontier, fidelity, cost, freq_loss and
         augmentation runs).
Outputs: in --out: fig_*.pdf and tables.tex.

Usage:
    python make_report_figures.py --audit          # list candidate sources
    python make_report_figures.py --results ./results --out ./report/figures
"""
import argparse, sys
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

# shared figure style, applied once so every figure matches
plt.rcParams.update({
    "figure.dpi": 300, "savefig.dpi": 300, "savefig.bbox": "tight",
    "font.size": 9, "axes.titlesize": 10, "axes.labelsize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.alpha": 0.25, "grid.linewidth": 0.5,
    "figure.figsize": (5.2, 3.2),          # fits a 12 cm column
})
TEAL, RED, GREY, GREEN, LIGHT = "#1C7293", "#B85042", "#64748B", "#2E7D5B", "#9DC3D4"
LABEL = {"medvae_4_3_2d": "4_3", "medvae_4_1_2d": "4_1",
         "medvae_8_4_2d": "8_4", "medvae_8_1_2d": "8_1"}


def audit(root: Path):
    """Report every frontier_summary and the run it came from, so the correct
    source can be chosen deliberately rather than by accident."""
    print("=" * 74)
    print("Audit: the same table appears in several directories, from different")
    print("runs. The seed_sd and n columns distinguish them.")
    print("=" * 74)
    for f in sorted(root.rglob("frontier_summary.csv")):
        df = pd.read_csv(f)
        cobb = df[df.task == "cobb"]
        print(f"\n{f.relative_to(root)}")
        print(f"   n = {int(cobb.n.iloc[0])}, {len(cobb)} configs")
        for _, r in cobb.iterrows():
            print(f"     {LABEL.get(r.config, r.config):<5} {r.error_mean:7.3f}"
                  f"   seed_sd {r.seed_sd:.4f}")
    print("\nSeed count is not stored in the CSV. A small seed_sd with a large")
    print("config count usually indicates a three-seed run; the command history")
    print("is the reliable record of each run's seed count.\n")

    print("Expected input files not found:")
    for want, why in [("*ladder*/mechanism*.csv", "the granularity dose-response"),
                      ("*per_angle*.csv", "the per-angle decomposition")]:
        if not list(root.rglob(want)):
            print(f"   missing  {want:<28} ({why})")
    print()


def read(root: Path, rel: str):
    p = root / rel
    if not p.exists():
        print(f"  skip: {rel} not found")
        return None
    return pd.read_csv(p)


def _esc(v):
    """Escape the LaTeX specials that appear in these values. Only underscores
    occur in practice (config names such as 4_3, filenames), but the others are
    cheap to guard. Values already containing intentional LaTeX, such as a
    $\\times$ from a formatter, are passed through untouched."""
    t = str(v)
    if "$" in t or "\\" in t:
        return t
    for a, b in (("_", "\\_"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#")):
        t = t.replace(a, b)
    return t


def latex_table(df, cols, fmt, caption, label):
    """Emit a booktabs table (with caption and label) for tables.tex."""
    out = ["% generated by make_report_figures.py --- do not edit by hand",
           "\\begin{table}[htbp]", "  \\centering",
           f"  \\caption{{{caption}}}", f"  \\label{{{label}}}",
           "  \\begin{tabular}{l" + "r" * (len(cols) - 1) + "}", "    \\toprule",
           "    " + " & ".join(c.replace("_", "\\_") for c in cols) + " \\\\",
           "    \\midrule"]
    for _, r in df.iterrows():
        cells = [fmt[i].format(r[c]) if i in fmt else _esc(r[c])
                 for i, c in enumerate(cols)]
        out.append("    " + " & ".join(cells) + " \\\\")
    out += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}"]
    return "\n".join(out)


# Figures
def fig_spectrum(root, out):
    df = read(root, "freq_loss/freq_loss_spectrum.csv")
    if df is None: return
    fig, ax = plt.subplots()
    for cfg, colour in [("medvae_4_1_2d", TEAL), ("medvae_8_1_2d", RED)]:
        d = df[df.config == cfg].sort_values("norm_freq")
        ax.plot(d.norm_freq, d.frac_content_lost, color=colour, lw=1.6,
                label=LABEL[cfg])
    ax.set_xlabel("normalised spatial frequency")
    ax.set_ylabel("residual-to-signal ratio")
    ax.legend(frameon=False)
    fig.savefig(out / "fig_frequency_spectrum.pdf"); plt.close(fig)
    print("  wrote fig_frequency_spectrum.pdf")


def fig_endplate(root, out):
    df = read(root, "freq_loss/endplate_summary.csv")
    if df is None: return
    fig, ax = plt.subplots(figsize=(4.4, 3.0))
    x = np.arange(len(df)); w = 0.36
    ax.bar(x - w/2, df.endplate_mean, w, color=TEAL, label="endplate",
           yerr=[df.endplate_mean - df.endplate_lo, df.endplate_hi - df.endplate_mean],
           capsize=3, error_kw={"lw": 0.8})
    ax.bar(x + w/2, df.centroid_mean, w, color=GREY, label="vertebral body",
           yerr=[df.centroid_mean - df.centroid_lo, df.centroid_hi - df.centroid_mean],
           capsize=3, error_kw={"lw": 0.8})
    for i, r in df.iterrows():
        ax.text(i, df.endplate_hi.max() * 1.06, f"{r.ratio_mean:.2f}$\\times$",
                ha="center", fontsize=8)
    ax.set_xticks(x); ax.set_xticklabels([LABEL.get(c, c) for c in df.config])
    ax.set_ylabel("mean squared reconstruction error")
    ax.legend(frameon=False)
    fig.savefig(out / "fig_endplate_concentration.pdf"); plt.close(fig)
    print("  wrote fig_endplate_concentration.pdf")


def fig_dissociation(root, out, frontier_rel):
    fid = read(root, "fidelity/recon_fidelity_summary.csv")
    fr = read(root, frontier_rel)
    if fid is None or fr is None: return
    pair = ["4_1", "8_4"]
    f = fid[fid.config.isin(pair)].set_index("config").loc[pair]
    c = fr[(fr.task == "cobb")].copy()
    c["short"] = c.config.map(LABEL)
    c = c[c.short.isin(pair)].set_index("short").loc[pair]

    fig, (a1, a2) = plt.subplots(1, 2, figsize=(5.6, 2.9))
    a1.bar(pair, f.ssim, color=[TEAL, GREY], width=0.55,
           yerr=[f.ssim - f.ssim_lo, f.ssim_hi - f.ssim], capsize=3,
           error_kw={"lw": 0.8})
    a1.set_ylabel("SSIM (higher is better)"); a1.set_ylim(0, 1.05)
    a1.set_title("reconstruction fidelity")
    a2.bar(pair, c.error_mean, color=[TEAL, GREY], width=0.55,
           yerr=[c.error_mean - c.error_lo, c.error_hi - c.error_mean], capsize=3,
           error_kw={"lw": 0.8})
    a2.set_ylabel("Cobb error, degrees (lower is better)")
    a2.set_ylim(bottom=min(c.error_lo) * 0.95)
    a2.set_title("clinical accuracy")
    fig.suptitle("both configurations: $16\\times$ compression, 36.0 kB",
                 fontsize=9, y=1.02)
    fig.savefig(out / "fig_dissociation.pdf"); plt.close(fig)
    print("  wrote fig_dissociation.pdf")


def fig_pareto(root, out, frontier_rel):
    cost = read(root, "cost/cost_benchmark.csv")
    fr = read(root, frontier_rel)
    if cost is None or fr is None: return
    fr = fr.copy(); fr["short"] = fr.config.map(LABEL)
    fig, axes = plt.subplots(1, 2, figsize=(6.0, 2.9))
    for ax, task, ylab in [(axes[0], "cobb", "Cobb error (deg)"),
                           (axes[1], "landmark", "landmark error")]:
        d = fr[fr.task == task].merge(cost, left_on="short", right_on="config")
        ax.scatter(d.latent_kb_fp32, d.error_mean, s=45, color=TEAL, zorder=3)
        for _, r in d.iterrows():
            ax.annotate(r.short, (r.latent_kb_fp32, r.error_mean),
                        textcoords="offset points", xytext=(5, 4), fontsize=8)
        ax.set_xscale("log"); ax.set_xlabel("latent size (kB, fp32)")
        ax.set_ylabel(ylab)
    fig.savefig(out / "fig_pareto.pdf"); plt.close(fig)
    print("  wrote fig_pareto.pdf")


def fig_augmentation(root, out):
    base = read(root, "curve/frontier_summary.csv")
    arms = {"conservative": "aug_cons", "moderate": "aug_mod", "aggressive": "aug"}
    if base is None: return
    rows = []
    for name, d in arms.items():
        a = read(root, f"{d}/frontier_summary.csv")
        if a is None: continue
        for task in ("cobb", "landmark"):
            b0 = base[(base.config == "medvae_4_1_2d") & (base.task == task)]
            a0 = a[(a.config == "medvae_4_1_2d") & (a.task == task)]
            if len(b0) and len(a0):
                rows.append({"preset": name, "task": task,
                             "pct": 100 * (1 - a0.error_mean.iloc[0] / b0.error_mean.iloc[0])})
    if not rows: return
    d = pd.DataFrame(rows)
    fig, ax = plt.subplots(figsize=(4.8, 3.0))
    x = np.arange(3); w = 0.36
    for i, (task, colour) in enumerate([("cobb", TEAL), ("landmark", RED)]):
        v = [d[(d.preset == p) & (d.task == task)].pct.iloc[0]
             for p in arms if len(d[(d.preset == p) & (d.task == task)])]
        ax.bar(x + (i - 0.5) * w, v, w, color=colour, label=task)
        for xi, vi in zip(x + (i - 0.5) * w, v):
            ax.text(xi, vi + 0.3, f"{vi:.1f}", ha="center", fontsize=7.5)
    ax.set_xticks(x); ax.set_xticklabels(list(arms))
    ax.set_ylabel("error reduction (%)"); ax.legend(frameon=False)
    fig.savefig(out / "fig_augmentation.pdf"); plt.close(fig)
    print("  wrote fig_augmentation.pdf")


# Tables
def tables(root, out, frontier_rel):
    txt = []
    fid = read(root, "fidelity/recon_fidelity_summary.csv")
    if fid is not None:
        d = fid.copy()
        d["PSNR"] = d.apply(lambda r: f"{r.psnr:.2f} [{r.psnr_lo:.2f}, {r.psnr_hi:.2f}]", axis=1)
        d["SSIM"] = d.apply(lambda r: f"{r.ssim:.3f} [{r.ssim_lo:.3f}, {r.ssim_hi:.3f}]", axis=1)
        d["compression"] = d.compression.map(lambda v: f"{v:.1f}$\\times$")
        txt.append(latex_table(d, ["config", "compression", "PSNR", "SSIM"], {},
                   "Reconstruction fidelity, content region only, with bootstrap "
                   "confidence intervals over 128 test images.", "tab:fidelity"))
    cost = read(root, "cost/cost_benchmark.csv")
    if cost is not None:
        d = cost.copy()
        d["storage"] = d.latent_kb_fp32.map(lambda v: f"{v:.1f} / {v/2:.1f}")
        d["ratio"] = d.ratio_vs_src_fp32.map(lambda v: f"{v:.1f}$\\times$")
        d["latency"] = d.encode_ms.map(lambda v: f"{v:.1f}")
        d["memory"] = d.encode_peak_mem_mb.map(lambda v: f"{v:.0f}")
        txt.append(latex_table(d, ["config", "latent_shape", "storage", "ratio",
                                   "latency", "memory"], {},
                   "Cost profile. Storage in kB at fp32/fp16; ratio against the "
                   "mean source file; latency in ms; peak memory in MB.",
                   "tab:cost"))
    fr = read(root, frontier_rel)
    if fr is not None:
        d = fr.copy(); d["config"] = d.config.map(lambda c: LABEL.get(c, c))
        d["error"] = d.apply(lambda r: f"{r.error_mean:.3f} [{r.error_lo:.3f}, {r.error_hi:.3f}]", axis=1)
        d["seed sd"] = d.seed_sd.map(lambda v: f"{v:.4f}")
        txt.append(latex_table(d, ["config", "task", "error", "seed sd"], {},
                   "Downstream task error for all configurations. "
                   f"Source: \\texttt{{{_esc(frontier_rel)}}}.", "tab:frontier"))
    (out / "tables.tex").write_text("\n\n".join(txt))
    print(f"  wrote tables.tex ({len(txt)} tables)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=Path("./results"))
    ap.add_argument("--out", type=Path, default=Path("./report/figures"))
    ap.add_argument("--frontier", default="curve/frontier_summary.csv",
                    help="Which run's frontier_summary.csv to use; --audit lists the candidates.")
    ap.add_argument("--audit", action="store_true")
    a = ap.parse_args()
    if not a.results.exists():
        sys.exit(f"results directory not found: {a.results}")
    if a.audit:
        audit(a.results); return
    a.out.mkdir(parents=True, exist_ok=True)
    print(f"reading from {a.results}, frontier source: {a.frontier}\n")
    fig_spectrum(a.results, a.out)
    fig_endplate(a.results, a.out)
    fig_dissociation(a.results, a.out, a.frontier)
    fig_pareto(a.results, a.out, a.frontier)
    fig_augmentation(a.results, a.out)
    tables(a.results, a.out, a.frontier)
    print(f"\nDone. Figures and tables.tex in {a.out}")
    print("tables.tex requires \\usepackage{booktabs} in the LaTeX preamble.")


if __name__ == "__main__":
    main()
